    private void btnIniciarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarActionPerformed
        try {
            if (btnIniciar.getText().equalsIgnoreCase("Conectar")) {
                int puerto = Integer.parseInt(campoPuertoServidor.getText());
                String ip = campoIPServidor.getText().trim();
                registro = LocateRegistry.getRegistry(ip, puerto);
                servidor = (CalculadoraSalarioRemota) registro.lookup("CalculadoraSalario");
                btnIniciar.setText("Desconectar");
                btnIniciar.setForeground(Color.RED);
                txtEstado.setText("Conectado");
                txtEstado.setForeground(Color.GREEN);
            } else if (btnIniciar.getText().equalsIgnoreCase("Desconectar")) {
                servidor = null;
                registro = null;
                btnIniciar.setText("Conectar");
                txtEstado.setText("Desconectado");
                btnIniciar.setForeground(Color.GREEN);
                txtEstado.setForeground(Color.RED);
            }
        } catch (Exception ex) {
            servidor = null;
            txtEstado.setText("Desconectado");
            JOptionPane.showMessageDialog(this, "ERROR AL CONECTAR: " + ex.getMessage());
        }

    }//GEN-LAST:event_btnIniciarActionPerformed

    private void btnIniciar1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciar1ActionPerformed
        // TODO add your handling code here:
        if (servidor == null) {
            JOptionPane.showMessageDialog(this, "Cliente OffLine, Conecte con el Servidor");
            return;
        }

        float horasTrabajadas = Float.parseFloat(campoHoras.getText());
        float valorPorHora = Float.parseFloat(campoValorHora.getText());

        Thread hilo = new Thread() {
            @Override
            public void run() {
                try {
                    System.out.println("Horas Trabajadas: " + horasTrabajadas);
                    System.out.println("Valor Por Hora: " + valorPorHora);
                    CalculoSalario.Salario salario = servidor.calcularSalario(horasTrabajadas, valorPorHora);
                    txtSalario.setText(salario.resultado + "");
                    txtMensaje.setText(salario.mensaje);
                } catch (RemoteException ex) {
                    JOptionPane.showMessageDialog(VentanaPrincipal.this, "ERROR con el servidor RMI " + ex.getMessage());
                    System.out.println("ERROR con el servidor RMI " + ex.getMessage());
                }
            }
        };

        hilo.start();
    }//GEN-LAST:event_btnIniciar1ActionPerformed

